 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
DECLARE
  v_base TEXT; v_title TEXT; v_n INT := 0; v_ex_id UUID; v_position INT;
  v_w JSONB; v_g JSONB; v_words TEXT[]; v_wnumbers INT[]; v_gnumbers INT[];
