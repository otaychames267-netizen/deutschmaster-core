-- Learning-assistance system (translation / evidence / explanation / saved
-- vocabulary) — foundation layer. Purely additive: nullable JSONB column on
-- each exercise table, a new per-user saved_expressions table, one new
-- pre-submission-safe translation RPC, and every existing scoring/reveal RPC
-- extended to also return the matching per-item learning_aids slice
-- alongside its existing correct/your_answer/correct_answer fields. No
-- existing column, table, RPC signature (only additive optional params), or
-- scoring logic is changed — original exam content and correctness checks
-- are untouched.
--
-- learning_aids shape (all optional, admin-authored, never AI-generated by
-- default):
--   {
--     "translation": { "text": "...", "questions": { "<itemKey>": "..." } },
--     "items": {
--       "<itemKey>": {
--         "evidence_text": "...", "evidence_translation": "...",
--         "keyword": "...",
--         "explanation_correct": "...", "explanation_wrong": "...",
--         "grammar_structure": "...", "grammar_example": "...", "grammar_translation": "..."
--       }
--     }
--   }
-- "translation" is safe to expose before an attempt is submitted (it never
-- reveals which option is correct). "items" is answer-adjacent and is only
-- ever returned by the scoring/reveal RPCs below, i.e. after the student has
-- submitted or explicitly requested the solution — the same boundary that
-- already protects correct_answer today.

ALTER TABLE lesen_exercises  ADD COLUMN IF NOT EXISTS learning_aids JSONB;
ALTER TABLE hoeren_exercises ADD COLUMN IF NOT EXISTS learning_aids JSONB;
ALTER TABLE sb_exercises     ADD COLUMN IF NOT EXISTS learning_aids JSONB;

-- ── Saved expressions (per-user vocabulary/notes) ──────────────────────────
CREATE TABLE IF NOT EXISTS saved_expressions (
  id          UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id     UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  skill       TEXT NOT NULL CHECK (skill IN ('lesen', 'hoeren', 'sprachbausteine')),
  exercise_id UUID,
  item_key    TEXT,
  category    TEXT NOT NULL CHECK (category IN ('wort', 'verb', 'feste_verbindung', 'redemittel', 'grammatikstruktur', 'wichtiger_ausdruck')),
  german      TEXT NOT NULL,
  grammar     TEXT,
  translation TEXT,
  explanation TEXT,
  example     TEXT,
  is_learned  BOOLEAN NOT NULL DEFAULT FALSE,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_saved_expressions_user ON saved_expressions(user_id, created_at DESC);

ALTER TABLE saved_expressions ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS saved_expressions_select_own ON saved_expressions;
CREATE POLICY saved_expressions_select_own ON saved_expressions
  FOR SELECT USING (user_id = auth.uid());

DROP POLICY IF EXISTS saved_expressions_insert_own ON saved_expressions;
CREATE POLICY saved_expressions_insert_own ON saved_expressions
  FOR INSERT WITH CHECK (user_id = auth.uid());

DROP POLICY IF EXISTS saved_expressions_update_own ON saved_expressions;
CREATE POLICY saved_expressions_update_own ON saved_expressions
  FOR UPDATE USING (user_id = auth.uid()) WITH CHECK (user_id = auth.uid());

DROP POLICY IF EXISTS saved_expressions_delete_own ON saved_expressions;
CREATE POLICY saved_expressions_delete_own ON saved_expressions
  FOR DELETE USING (user_id = auth.uid());

-- ── Pre-submission-safe translation RPC ────────────────────────────────────
-- Returns ONLY learning_aids->'translation' (never ->'items', which is
-- answer-adjacent) — safe to call any time the student can already see the
-- exercise text, gated by the identical has_plan_access/free-sample check
-- every content table already enforces.
CREATE OR REPLACE FUNCTION public.get_exercise_translation(p_skill TEXT, p_exercise_id UUID)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public'
AS $function$
DECLARE
  v_uid UUID := auth.uid();
  v_translation JSONB;
BEGIN
  IF p_skill = 'lesen' THEN
    IF NOT (public.has_plan_access(v_uid, 'schriftlich') OR public.is_d17_staff(v_uid)
            OR EXISTS (SELECT 1 FROM lesen_exercises WHERE id = p_exercise_id AND is_free_sample = true)) THEN
      RAISE EXCEPTION 'Forbidden: active schriftlich subscription required';
    END IF;
    SELECT learning_aids -> 'translation' INTO v_translation FROM lesen_exercises WHERE id = p_exercise_id;
  ELSIF p_skill = 'hoeren' THEN
    IF NOT (public.has_plan_access(v_uid, 'schriftlich') OR public.is_d17_staff(v_uid)
            OR EXISTS (SELECT 1 FROM hoeren_exercises WHERE id = p_exercise_id AND is_free_sample = true)) THEN
      RAISE EXCEPTION 'Forbidden: active schriftlich subscription required';
    END IF;
    SELECT learning_aids -> 'translation' INTO v_translation FROM hoeren_exercises WHERE id = p_exercise_id;
  ELSIF p_skill = 'sprachbausteine' THEN
    IF NOT (public.has_plan_access(v_uid, 'schriftlich') OR public.is_d17_staff(v_uid)
            OR EXISTS (SELECT 1 FROM sb_exercises WHERE id = p_exercise_id AND is_free_sample = true)) THEN
      RAISE EXCEPTION 'Forbidden: active schriftlich subscription required';
    END IF;
    SELECT learning_aids -> 'translation' INTO v_translation FROM sb_exercises WHERE id = p_exercise_id;
  ELSE
    RAISE EXCEPTION 'Invalid skill: %', p_skill;
  END IF;

  RETURN COALESCE(v_translation, 'null'::JSONB);
END;
$function$;

-- ── Extend scoring/reveal RPCs to also return per-item learning_aids ───────
-- Each function is unchanged except for one extra SELECT of the parent
-- exercise's learning_aids before the loop, and one extra key merged into
-- the existing per-item jsonb_build_object. Grading logic, score math, and
-- the attempt INSERT (where present) are byte-for-byte identical to before.

CREATE OR REPLACE FUNCTION public.score_and_save_lesen_t1(p_exercise_id uuid, p_answers jsonb)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
DECLARE
  v_uid    UUID := auth.uid();
  v_results JSONB := '[]'::JSONB;
  v_score  INT := 0;
  v_total  INT := 0;
  v_t      RECORD;
  v_chosen TEXT;
  v_ok     BOOLEAN;
  v_attempt UUID;
  v_aids   JSONB;
BEGIN
  IF NOT (public.has_plan_access(v_uid, 'schriftlich') OR public.is_d17_staff(v_uid)
          OR EXISTS (SELECT 1 FROM lesen_exercises WHERE id = p_exercise_id AND is_free_sample = true)) THEN
    RAISE EXCEPTION 'Forbidden: active schriftlich subscription required';
  END IF;

  SELECT learning_aids -> 'items' INTO v_aids FROM lesen_exercises WHERE id = p_exercise_id;

  FOR v_t IN SELECT position, correct_headline FROM lesen_t1_texts WHERE exercise_id = p_exercise_id ORDER BY position LOOP
    v_total := v_total + 1;
    v_chosen := p_answers ->> v_t.position::TEXT;
    v_ok := (UPPER(COALESCE(v_chosen,'')) = UPPER(v_t.correct_headline));
    IF v_ok THEN v_score := v_score + 1; END IF;
    v_results := v_results || jsonb_build_object(
      'position', v_t.position, 'correct', v_ok,
      'your_answer', COALESCE(v_chosen,''),
      'correct_answer', CASE WHEN v_ok THEN v_chosen ELSE v_t.correct_headline END,
      'learning_aids', COALESCE(v_aids -> v_t.position::TEXT, 'null'::JSONB)
    );
  END LOOP;

  INSERT INTO lesen_attempts (user_id, exercise_id, teil, score, total, answers, results)
  VALUES (v_uid, p_exercise_id, 1, v_score, v_total, p_answers, v_results)
  RETURNING id INTO v_attempt;

  RETURN jsonb_build_object('score', v_score, 'total', v_total, 'results', v_results, 'attempt_id', v_attempt);
END;
$function$;

