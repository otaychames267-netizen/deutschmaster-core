-- Documentation-only update: the Mündlich evaluation feedback JSONB shape
-- grew from 4 per-Teil criteria to 7 (added task_completion/Aufgabenbewältigung,
-- intelligibility/Verständlichkeit, interaction/Interaktion), plus new
-- top-level strengths/weaknesses/recurring_patterns/better_formulations
-- fields — see muendlich-relay/src/muendlich-evaluator.ts and
-- src/lib/grading/muendlich-evaluator.ts. `feedback` is JSONB (schemaless),
-- so no ALTER TABLE is needed here — this migration exists only so the
-- column comment (the shape documentation) doesn't silently go stale, same
-- convention as 20260708120000_muendlich_evaluation_75pt.sql.
--
-- Also fixes a real (not just documentation) discrepancy: the deployed relay
-- previously called Gemini 2.5 Flash directly for evaluation despite an
-- earlier commit claiming a migration to Claude Sonnet 5 — that migration
-- had only ever touched the unused main-app copy of this file. The relay's
-- copy now actually calls Claude too (same tool-forced-JSON pattern already
-- used for Schreiben grading), so `muendlich_evaluations.model` will read
-- "claude-sonnet-5" for evaluations generated from this point forward;
-- historical rows keep whatever model actually produced them.
COMMENT ON COLUMN muendlich_evaluations.feedback IS
  'Expected shape (100% German content, generated by muendlich-evaluator.ts via Claude Sonnet 5):
   {
     "teil_breakdown": [
       { "teil": 1, "score": 20,
         "task_completion": "...", "pronunciation": "...", "intelligibility": "...",
         "vocabulary": "...", "grammar": "...", "fluency": "...", "interaction": "..." },
       { "teil": 2, "score": 18, ... }, { "teil": 3, "score": 19, ... }
     ],
     "strengths": ["...", "..."],
     "weaknesses": ["...", "..."],
     "recurring_patterns": [ { "pattern": "...", "examples": ["exact quote", "..."], "improvement_tip": "..." } ],
     "error_correction_matrix": [ { "original": "exact quote from transcript", "correction": "corrected German", "explanation": "..." } ],
     "better_formulations": [ { "original": "correct but basic phrasing", "improved": "...", "why_better": "..." } ],
     "vocabulary_enrichment": [ { "weak_term": "...", "suggestions": ["...", "..."], "context": "..." } ],
     "pacing_tips": "...",
     "summary": "...",
     "closing_statement": "..."  -- ALWAYS the fixed, exact motivational text —
       -- appended in code (MUENDLICH_CLOSING_STATEMENT constant), never
       -- generated by the model, so the wording is byte-for-byte guaranteed
       -- regardless of what the LLM produces for everything else.
   }
   Older rows (generated before 2026-08-22) only have the original 4 per-Teil
   criteria (pronunciation/vocabulary/grammar/fluency) and lack the
   strengths/weaknesses/recurring_patterns/better_formulations fields — every
   reader of this column must treat all new fields as optional.';
