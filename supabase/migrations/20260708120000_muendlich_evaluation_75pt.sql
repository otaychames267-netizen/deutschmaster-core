-- Mündlich evaluation scoring restructure: official telc point distribution is
-- PER-TEIL (Teil 1/2/3 = 25 points each, 75 total), not per-criterion. The 4
-- criteria (Pronunciation/Vocabulary/Grammar/Fluency) remain the ASSESSMENT
-- LENS the AI uses to arrive at each Teil's score, but they are no longer
-- separate point buckets — moved into the qualitative `feedback` JSONB as a
-- per-Teil breakdown instead of 4 flat numeric columns.
--
-- Table has zero real rows (verified before this migration — Phase 2 content/
-- exam flow isn't live yet), so this is a clean structural replacement, not a
-- data migration.

ALTER TABLE muendlich_evaluations
  DROP COLUMN IF EXISTS pronunciation_score,
  DROP COLUMN IF EXISTS grammar_score,
  DROP COLUMN IF EXISTS vocabulary_score,
  DROP COLUMN IF EXISTS fluency_score;

ALTER TABLE muendlich_evaluations
  ADD COLUMN IF NOT EXISTS teil1_score INT,
  ADD COLUMN IF NOT EXISTS teil2_score INT,
  ADD COLUMN IF NOT EXISTS teil3_score INT;

-- overall_score / passed had 0-100-scale constraints from the old 4x25 model —
-- drop and recreate at the correct 0-75 scale (telc pass threshold ≈ 60% → 45/75).
ALTER TABLE muendlich_evaluations DROP CONSTRAINT IF EXISTS muendlich_evaluations_overall_score_check;
ALTER TABLE muendlich_evaluations
  ADD CONSTRAINT muendlich_evaluations_teil1_score_check CHECK (teil1_score BETWEEN 0 AND 25),
  ADD CONSTRAINT muendlich_evaluations_teil2_score_check CHECK (teil2_score BETWEEN 0 AND 25),
  ADD CONSTRAINT muendlich_evaluations_teil3_score_check CHECK (teil3_score BETWEEN 0 AND 25),
  ADD CONSTRAINT muendlich_evaluations_overall_score_check CHECK (overall_score BETWEEN 0 AND 75),
  ADD CONSTRAINT muendlich_evaluations_overall_sum_check CHECK (overall_score = teil1_score + teil2_score + teil3_score);

ALTER TABLE muendlich_evaluations ALTER COLUMN teil1_score SET NOT NULL;
ALTER TABLE muendlich_evaluations ALTER COLUMN teil2_score SET NOT NULL;
ALTER TABLE muendlich_evaluations ALTER COLUMN teil3_score SET NOT NULL;

COMMENT ON COLUMN muendlich_evaluations.teil1_score IS 'Präsentation, 0-25.';
COMMENT ON COLUMN muendlich_evaluations.teil2_score IS 'Gespräch über ein Thema, 0-25.';
COMMENT ON COLUMN muendlich_evaluations.teil3_score IS 'Etwas gemeinsam planen, 0-25.';
COMMENT ON COLUMN muendlich_evaluations.overall_score IS 'Sum of the three Teil scores, 0-75 (telc official total).';
COMMENT ON COLUMN muendlich_evaluations.passed IS 'overall_score >= 45 (telc pass threshold, ~60%).';
COMMENT ON COLUMN muendlich_evaluations.feedback IS
  'Expected shape (100% German content, generated by muendlich-evaluator.ts):
   {
     "teil_breakdown": [
       { "teil": 1, "score": 20, "pronunciation": "...", "vocabulary": "...", "grammar": "...", "fluency": "..." },
       { "teil": 2, "score": 18, ... }, { "teil": 3, "score": 19, ... }
     ],
     "error_correction_matrix": [ { "original": "exact quote from transcript", "correction": "corrected German", "explanation": "..." } ],
     "vocabulary_enrichment": [ { "weak_term": "...", "suggestions": ["...", "..."], "context": "..." } ],
     "pacing_tips": "...",
     "summary": "...",
     "closing_statement": "..."  -- ALWAYS the fixed, exact motivational text —
       -- appended in code (MUENDLICH_CLOSING_STATEMENT constant), never
       -- generated by the model, so the wording is byte-for-byte guaranteed
       -- regardless of what the LLM produces for everything else.
   }';
